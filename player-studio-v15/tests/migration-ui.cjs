const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const {chromium}=require('C:/Users/1/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
  const root=path.resolve(__dirname,'../..'),qa=path.join(root,'.work/studio-qa');
  const runtime=JSON.parse(fs.readFileSync(process.env.STUDIO_RUNTIME||path.join(root,'.work/studio-final-test/runtime.json'),'utf8'));
  const seed=path.join(qa,'seed.efsave'),apk=path.join(root,'73efootball-V13.apk');
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1600,height:1060}});
  await page.goto(runtime.url);await page.waitForFunction(()=>window.__studio?.project);
  const uid=await page.evaluate(()=>window.__studio.project.package_id);
  await page.locator('[data-page="migration"]').click();
  await page.locator('#migration-save').fill(seed);await page.locator('#migration-apk').fill(apk);
  await page.locator('[data-action="read-players"]').click();
  await page.locator('[name="native-player"]').first().check();
  const exportResponse=page.waitForResponse(r=>r.url().endsWith('/api/package/export'));
  await page.locator('[data-action="export-snapshot"]').click();
  const response=await exportResponse,snapshot=await response.json();assert.equal(response.status(),200,JSON.stringify(snapshot));assert.equal(snapshot.package_id,uid);
  await page.waitForFunction(()=>window.__studio.project.card_id!==null);
  await page.evaluate(()=>window.__studio.flushSave());
  const selected=await page.evaluate(()=>({id:window.__studio.project.card_id,serial:window.__studio.project.serial}));
  await page.locator('[name="native-player"]').nth(1).check();
  const badResponse=page.waitForResponse(r=>r.url().endsWith('/api/package/export'));
  await page.locator('[data-action="export-snapshot"]').click();
  assert.equal((await badResponse).status(),400,'bound project must reject another instance');
  await page.locator('[data-migration-mode="import"]').click();
  await page.locator('#migration-save').fill(path.join(qa,'seed-missing.efsave'));
  await page.locator('#migration-package').fill(snapshot.output);
  const inspectResponse=page.waitForResponse(r=>r.url().endsWith('/api/package/inspect'));
  await page.locator('[data-action="inspect-package"]').click();assert.equal((await inspectResponse).status(),200);
  const planResponse=page.waitForResponse(r=>r.url().endsWith('/api/migration/plan'));
  await page.locator('[data-action="migration-plan"]').click();
  const plan=await (await planResponse).json();assert.equal(plan.package_id,uid);
  assert.equal(plan.action,'insert','must restore the absent player and training journal');
  await page.waitForFunction(()=>!document.querySelector('[data-action="migration-apply"]').disabled);
  const importResponse=page.waitForResponse(r=>r.url().endsWith('/api/migration/import'));
  await page.locator('[data-action="migration-apply"]').click();
  const imported=await importResponse,result=await imported.json();assert.equal(imported.status(),200,JSON.stringify(result));
  assert.ok(fs.existsSync(result.output));assert.ok(fs.existsSync(result.backup));
  await page.waitForFunction(()=>document.querySelector('[data-action="migration-apply"]').disabled);
  await page.screenshot({path:path.join(qa,'07-migration-success.png'),fullPage:true});
  const report={status:'passed',fixture:'V13 APK seed; not user progress',package_id:uid,selected,source:seed,target:path.join(qa,'seed-missing.efsave'),snapshot:snapshot.output,output:result.output,backup:result.backup,plan_action:plan.action,wrong_instance_rejected:true};
  fs.writeFileSync(path.join(qa,'migration-ui-result.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
